USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS USER_REGISTRATION_DB;

CREATE SCHEMA IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS;

USE WAREHOUSE COMPUTE_WH;
USE DATABASE USER_REGISTRATION_DB;
USE SCHEMA ANALYTICS;

CREATE TABLE IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS (
  REGISTRATION_DATE DATE,
  NEW_USERS BIGINT
);

CREATE VIEW IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS_TOTAL AS
SELECT REGISTRATION_DATE,
       NEW_USERS,
       SUM(NEW_USERS) OVER (ORDER BY REGISTRATION_DATE) AS TOTAL_USERS
FROM USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS;

SELECT CURRENT_ROLE() AS role,
       CURRENT_USER() AS username,
       CURRENT_WAREHOUSE() AS warehouse,
       CURRENT_DATABASE() AS database,
       CURRENT_SCHEMA() AS schema;

SELECT REGISTRATION_DATE, NEW_USERS, TOTAL_USERS
FROM USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS_TOTAL
ORDER BY REGISTRATION_DATE;

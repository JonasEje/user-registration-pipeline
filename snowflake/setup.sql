USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS USER_REGISTRATION_DB;

CREATE SCHEMA IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS;

USE WAREHOUSE COMPUTE_WH;
USE DATABASE USER_REGISTRATION_DB;
USE SCHEMA ANALYTICS;

CREATE TABLE IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS.REGISTRATIONS (
  USER_ID VARCHAR,
  REGISTERED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS (
  REGISTRATION_DATE DATE,
  NEW_USERS BIGINT
);

CREATE VIEW IF NOT EXISTS USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS_TOTAL AS
SELECT REGISTRATION_DATE,
       NEW_USERS,
       SUM(NEW_USERS) OVER (ORDER BY REGISTRATION_DATE) AS TOTAL_USERS
FROM USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS;

CREATE OR REPLACE PROCEDURE USER_REGISTRATION_DB.ANALYTICS.REFRESH_DAILY_REGISTRATIONS()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  IF ((SELECT COUNT(*) FROM USER_REGISTRATION_DB.ANALYTICS.REGISTRATIONS) = 0) THEN
    RETURN 'No registrations found; DAILY_REGISTRATIONS left unchanged';
  END IF;

  INSERT OVERWRITE INTO USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS
    (REGISTRATION_DATE, NEW_USERS)
  SELECT TO_DATE(CONVERT_TIMEZONE('UTC', REGISTERED_AT)) AS REGISTRATION_DATE,
         COUNT(*) AS NEW_USERS
  FROM USER_REGISTRATION_DB.ANALYTICS.REGISTRATIONS
  GROUP BY TO_DATE(CONVERT_TIMEZONE('UTC', REGISTERED_AT));

  RETURN 'DAILY_REGISTRATIONS refreshed';
END;
$$;

CREATE OR REPLACE TASK USER_REGISTRATION_DB.ANALYTICS.REFRESH_DAILY_REGISTRATIONS_TASK
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 10 0 * * * UTC'
AS
  CALL USER_REGISTRATION_DB.ANALYTICS.REFRESH_DAILY_REGISTRATIONS();

ALTER TASK USER_REGISTRATION_DB.ANALYTICS.REFRESH_DAILY_REGISTRATIONS_TASK RESUME;

SELECT CURRENT_ROLE() AS role,
       CURRENT_USER() AS username,
       CURRENT_WAREHOUSE() AS warehouse,
       CURRENT_DATABASE() AS database,
       CURRENT_SCHEMA() AS schema;

SELECT REGISTRATION_DATE, NEW_USERS, TOTAL_USERS
FROM USER_REGISTRATION_DB.ANALYTICS.DAILY_REGISTRATIONS_TOTAL
ORDER BY REGISTRATION_DATE;
